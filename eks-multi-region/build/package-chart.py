#!/usr/bin/env python3
"""Package the rendered app manifest as a Helm chart and emit the chart-repo ConfigMap.

Usage:
    python3 build/package-chart.py <rendered-app.yaml> <out-configmap.yaml>

── WHY A HELM CHART AT ALL ──────────────────────────────────────────────────────────────

Argo CD accepts three source types: git, an HTTP Helm repository, and OCI. This demo's
subnets have no NAT, so git is out -- the repo-server cannot reach any external git host. ECR as an
OCI registry WOULD work, but upstream Argo CD authenticates to a registry with a static
username/password Secret (verified against Argo's own OCI docs -- there is no IAM or
credential-helper path), and an ECR token dies after 12 hours. A refresher CronJob's failure
mode is "Argo cannot sync", which on stage is indistinguishable from the conflict this demo
exists to disprove. So: an in-cluster HTTP Helm repo. No credentials, nothing to expire.

── WHY THE CHART IS BUILT FROM THE RENDERED MANIFEST ────────────────────────────────────

The chart's only template is k8s/app.yaml itself, copied in VERBATIM after placeholder
substitution. That matters: Argo CD must manage the same Deployment the installer applies
and that ARC later scales. Maintaining a separate copy of the app spec inside a chart would
let the two drift, and the failure would be Argo reporting OutOfSync against a difference
nobody introduced on purpose -- or worse, Argo "correcting" the live app to a stale spec.
One source, no drift possible.

The manifest must be RENDERED first: Argo does not know about ${PLACEHOLDER}, so an
unrendered chart would ship literal placeholders into the cluster.

── WHY NO HELM BINARY ───────────────────────────────────────────────────────────────────

A chart archive is a gzipped tar with a known layout and index.yaml is small YAML with a
sha256 digest. Both are produced here with the standard library, so this runs in the deploy
job as-is -- adding helm to that image for a 3 KB tarball would be a build dependency for
no benefit.

── THE VERSION IS A TIMESTAMP, DELIBERATELY ─────────────────────────────────────────────

Argo CD's repo-server caches resolved manifests keyed by chart VERSION. Republish the same
version with different bytes and it may serve the cached copy indefinitely -- the symptom is
"Argo just doesn't notice", with nothing in its UI suggesting why. A monotonically
increasing version avoids that entirely, and the Application targets `*` so it always
resolves the newest.

A content hash would be tidier (no version churn when nothing changed) but content hashes
are not ORDERED, so `*` could resolve backwards to an older chart. Monotonic beats tidy
here. The cost is a new version on every deploy even when the app is unchanged, which for a
demo is harmless and arguably shows the loop working.
"""

from __future__ import annotations

import base64
import hashlib
import io
import pathlib
import sys
import tarfile
import time

CHART_NAME = "orders-api"
# Namespace and names must match k8s/chart-repo.yaml, which serves this.
REPO_NAMESPACE = "argocd"
CONFIGMAP_NAME = "chart-repo-content"


def chart_version() -> str:
    """Monotonic, plain semver. Minutes since 2026-01-01 keeps the patch a sane size."""
    epoch_2026 = 1767225600  # 2026-01-01T00:00:00Z
    minutes = max(0, int((time.time() - epoch_2026) // 60))
    return f"0.1.{minutes}"


def build_chart_tgz(app_yaml: str, version: str) -> bytes:
    """A Helm chart archive: <name>/Chart.yaml + <name>/templates/*.

    Written by hand rather than with `helm package` -- see the module docstring. The layout
    is the part that matters: everything lives under a single top-level directory named for
    the chart, and Helm rejects an archive that does not.
    """
    chart_yaml = (
        "apiVersion: v2\n"
        f"name: {CHART_NAME}\n"
        f"version: {version}\n"
        "description: >-\n"
        "  The demo application, packaged so Argo CD can manage it. Generated by\n"
        "  build/package-chart.py from the RENDERED k8s/app.yaml -- do not hand-edit.\n"
        "type: application\n"
    )

    buf = io.BytesIO()
    # mtime pinned to 0 and a fixed member order so the archive is reproducible for a given
    # input. Without that, two runs over identical content produce different bytes and the
    # sha256 in index.yaml churns for no reason.
    with tarfile.open(fileobj=buf, mode="w:gz", format=tarfile.GNU_FORMAT) as tar:
        for name, content in (
            (f"{CHART_NAME}/Chart.yaml", chart_yaml),
            (f"{CHART_NAME}/templates/app.yaml", app_yaml),
        ):
            data = content.encode()
            info = tarfile.TarInfo(name)
            info.size = len(data)
            info.mtime = 0
            info.mode = 0o644
            tar.addfile(info, io.BytesIO(data))
    return buf.getvalue()


def build_index(version: str, tgz: bytes, filename: str) -> str:
    digest = hashlib.sha256(tgz).hexdigest()
    # `urls` is RELATIVE. nginx serves the archive from the same directory as index.yaml, so
    # an absolute URL here would hardcode a Service name into the chart metadata.
    return (
        "apiVersion: v1\n"
        "entries:\n"
        f"  {CHART_NAME}:\n"
        f"    - apiVersion: v2\n"
        f"      name: {CHART_NAME}\n"
        f"      version: {version}\n"
        f"      created: '1970-01-01T00:00:00Z'\n"
        f"      digest: {digest}\n"
        f"      urls:\n"
        f"        - {filename}\n"
        "generated: '1970-01-01T00:00:00Z'\n"
    )


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__.split("\n\n")[1].strip(), file=sys.stderr)
        return 2
    src, dest = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])

    app_yaml = src.read_text(encoding="utf-8")
    if "${" in app_yaml:
        # An unrendered manifest would put literal placeholders into the cluster via Argo,
        # which does not substitute them. render-manifest.py must run first.
        leftover = sorted(set(__import__("re").findall(r"\$\{[A-Z][A-Z0-9_]*\}", app_yaml)))
        print(
            f"ERROR: {src} still contains placeholders {leftover}. "
            f"Run build/render-manifest.py on it before packaging.",
            file=sys.stderr,
        )
        return 1
    if "kind: Deployment" not in app_yaml:
        # The whole point is for Argo to manage the Deployment ARC scales. A chart without
        # one would sync green and manage nothing that matters.
        print(f"ERROR: {src} contains no Deployment.", file=sys.stderr)
        return 1

    version = chart_version()
    filename = f"{CHART_NAME}-{version}.tgz"
    tgz = build_chart_tgz(app_yaml, version)
    index = build_index(version, tgz, filename)

    # binaryData for the archive (base64, required for non-UTF8), plain data for index.yaml.
    # A few KB total -- comfortably under the 1 MiB ConfigMap limit, which is why this needs
    # no S3 fetch, no extra image and no pod IAM.
    manifest = (
        "---\n"
        "apiVersion: v1\n"
        "kind: ConfigMap\n"
        "metadata:\n"
        f"  name: {CONFIGMAP_NAME}\n"
        f"  namespace: {REPO_NAMESPACE}\n"
        "  annotations:\n"
        "    eks-mr-demo/generated-by: build/package-chart.py\n"
        f"    eks-mr-demo/chart-version: '{version}'\n"
        "data:\n"
        "  index.yaml: |\n"
        + "".join(f"    {line}\n" for line in index.rstrip("\n").split("\n"))
        + "binaryData:\n"
        f"  {filename}: {base64.b64encode(tgz).decode()}\n"
    )
    dest.write_text(manifest, encoding="utf-8")

    print(
        f"packaged {CHART_NAME} {version}: {len(tgz)} bytes archive, "
        f"{len(manifest)} bytes ConfigMap -> {dest}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
